<script setup lang="ts">
/**
 * 📋 RegionMemberNames — รายชื่อเล่นของสมาชิกในภูมิภาคหนึ่ง (คั่นด้วยจุลภาค)
 *
 * 🎯 เหตุผลที่แยกออกมาเป็นคอมโพเนนต์ ไม่เขียน `<span>{{ names.join(', ') }}</span>` ตรง ๆ:
 *    ข้อความไทย **ไม่มีช่องว่างระหว่างคำ** ⇒ เบราว์เซอร์ตัดบรรทัดด้วยพจนานุกรม
 *    ผลคือชื่อคนถูกตัด **กลางชื่อ** ได้ (เช่น "สม" ขึ้นบรรทัดบน "ชาย" ตกบรรทัดล่าง)
 *    ผู้ใช้เห็นเป็นชื่อที่ขาด และแยกไม่ออกว่าชื่อไหนจบตรงไหน — ข้อมูลอ่านอย่างเดียว
 *    ที่ "ถูกตัด" โดยไม่มีอะไรฟ้อง (skills.md:679)
 *
 * 🔴 กลไกที่ทำให้ถูกต้อง (สองอย่างนี้ต้องอยู่คู่กัน ห้ามแก้อย่างใดอย่างหนึ่ง):
 *    1. `whitespace-nowrap` ที่ **แต่ละชื่อ** ⇒ ชื่อหนึ่งไม่ถูกตัดกลางคำเด็ดขาด
 *    2. ช่องว่าง **หลังจุลภาค** ที่คั่นระหว่างชื่อ ⇒ เป็นจุดตัดบรรทัดธรรมชาติ
 *    ⚠️ ถ้าเปลี่ยนตัวคั่นเป็น `,` (ไม่มีช่องว่าง) จะไม่เหลือจุดตัดบรรทัดเลย
 *       ⇒ ทั้งรายชื่อกลายเป็นแถวเดียวยาว ๆ ที่ล้นออกนอกจอ — บั๊กที่คอมโพเนนต์นี้กันไว้
 *       (เทสต์บังคับว่าตัวคั่นต้องมีช่องว่าง)
 *
 * 📌 ไม่ตัดชื่อด้วย `truncate`/`line-clamp` — นี่คือแหล่งอ้างอิงรายชื่อจริงของผู้ใช้
 *    (ป้ายบนแผนภาพเวนมีที่จำกัดจึงย่อได้ แต่ที่นี่ต้องครบ)
 *
 * ⚠️ ข้อจำกัดที่ยอมรับ: ชื่อเดียวที่ยาวกว่าความกว้างคอลัมน์จะล้นออกเล็กน้อย
 *    (แลกกับการไม่ตัดชื่อกลางคำ) — ชื่อเล่น/ชื่อจริงไทยยาวไม่ถึงขนาดนั้นในทางปฏิบัติ
 */
defineProps<{
  /** ชื่อเล่น เรียงตามเลขที่แล้ว — ลำดับนี้คือลำดับที่แสดง */
  names: string[]
}>()
</script>

<template>
  <span>
    <template v-for="(name, index) in names" :key="`${index}-${name}`">
      <span class="whitespace-nowrap">{{ name }}</span>
      <!--
        🔴 ตัวคั่นต้องเป็น **interpolation** (`{{ ', ' }}`) ห้ามเขียนเป็นข้อความตรง ๆ (`, `)
           เพราะ compiler ของ Vue ตัดช่องว่างท้าย element ทิ้งในโหมด `condense`
           ⇒ เหลือแค่ `,` ไม่มีช่องว่าง ⇒ **ไม่เหลือจุดตัดบรรทัดเลย** ทั้งรายชื่อกลายเป็น
             แถวเดียวยาวล้นจอ (เทสต์ `RegionMemberNames.spec.ts` จับเคสนี้ไว้แล้ว)
      -->
      <span v-if="index < names.length - 1">{{ ', ' }}</span>
    </template>
  </span>
</template>
