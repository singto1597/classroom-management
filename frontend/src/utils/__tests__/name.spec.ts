import { describe, it, expect } from 'vitest';
import { displayName } from '@/utils/name';

/**
 * 🔒 ล็อกนโยบายชื่อบนหน้าจอเงิน (2026-11-25)
 *
 * บิล/เอกสาร/รายการเงินต้องเป็น **ชื่อเต็มทางการ** = คำนำหน้า + ชื่อ + นามสกุล
 * — ห้ามต่อชื่อเล่นในวงเล็บ ("นายพัฒนพล(สิงโต)" ❌ → "นายพัฒนพล สุธรรม" ✅)
 * ชื่อไทยมาก่อนเสมอ; ใช้คู่ชื่ออังกฤษเฉพาะเมื่อไม่มีชื่อไทย (ไม่ผสมไทย/อังกฤษ)
 */

describe('displayName', () => {
  it('ประกอบคำนำหน้า + ชื่อ + นามสกุล และไม่ต่อชื่อเล่น', () => {
    expect(
      displayName({
        prefix: 'นาย',
        first_name: 'พัฒนพล',
        last_name: 'สุธรรม',
      }),
    ).toBe('นาย พัฒนพล สุธรรม');
  });

  it('ไม่ใช้ชื่อเล่นแม้จะถูกส่งมาในออบเจกต์', () => {
    const parts = {
      prefix: 'เด็กชาย',
      first_name: 'สมชาย',
      last_name: 'ใจดี',
    } as Record<string, string>;
    // คีย์ชื่อเล่นไม่ใช่ส่วนหนึ่งของสัญญา — ถ้าผู้เรียกส่งมาก็ต้องไม่ถูกพิมพ์
    parts.nickname = 'โต';
    expect(displayName(parts)).toBe('เด็กชาย สมชาย ใจดี');
  });

  it('ไม่มีคำนำหน้าได้ — ชื่อไทยยังมาก่อนชื่ออังกฤษ', () => {
    expect(displayName({ first_name: 'สมหญิง', last_name: 'รักเรียน' })).toBe(
      'สมหญิง รักเรียน',
    );
  });

  it('ไม่มีชื่อไทย → ใช้คู่ชื่ออังกฤษ', () => {
    expect(
      displayName({
        prefix: 'Mr.',
        first_name_en: 'John',
        last_name_en: 'Doe',
      }),
    ).toBe('John Doe');
  });

  it('ไม่มีข้อมูลเลย → สตริงว่าง (ไม่พิมพ์ช่องว่างค้าง)', () => {
    expect(displayName({})).toBe('');
  });
});
