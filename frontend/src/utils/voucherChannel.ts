/** ฟิลด์ขั้นต่ำที่ต้องใช้ — subset ของ `VoucherFields` (เทสต์ได้ด้วยออบเจ็กต์จิ๋ว) */
export interface VoucherChannelFields {
  account_kind?: string | null;
  bank_name?: string | null;
  bank_account_no?: string | null;
  bank_account_name?: string | null;
}

/** ค่าที่รู้จัก — `'transfer'` เท่านั้นที่อนุญาตให้ขึ้นว่า "โอนเข้าบัญชี" */
const KIND_CASH = 'cash';
const KIND_TRANSFER = 'transfer';

export function voucherChannel(d: VoucherChannelFields | null | undefined): string | null {
  if (!d) return null;
  if (d.account_kind === KIND_CASH) return 'เงินสด';
  // 🔴 ด่านปิดท้ายแบบ whitelist — บรรทัดนี้ **ตายที่ระดับชนิด**
  //    (`AccountKind = 'cash' | 'transfer'`) แต่ **ไม่ตายที่ runtime**
  //
  //    ⚠️ ด่านนี้ **กลืนเคส `undefined`/`null`/`''` ไปด้วย** ⇒ เขียน `!d.account_kind`
  //       เพิ่มอีกชั้นก็ไม่ผิด แต่ **เป็นบรรทัดที่ไม่มีเทสต์ใดป้องกันได้** (พิสูจน์แล้ว:
  //       สลับเป็น `=== null` แล้วเทสต์ยังเขียวทั้ง 8 ตัว เพราะด่านนี้จับให้อยู่แล้ว)
  //       ⇒ ตัดออกตามกฎ "บรรทัดที่ mutant รอดโดยไม่มีคำอธิบาย = บรรทัดที่ต้องตัดหรือต้องมีเทสต์"
  //       (ดู `docs/skills.md` เรื่อง equivalent mutant)
  if (d.account_kind !== KIND_TRANSFER) return null;
  const parts = [d.bank_name, d.bank_account_no, d.bank_account_name].filter(
    (part): part is string => Boolean(part),
  );
  // 🏦 โอนแต่ยังไม่ได้กรอกรายละเอียด ⇒ "โอนเข้าบัญชี" เฉย ๆ **ไม่ใช่ช่องว่าง**
  //    (ต่างจาก `null` ข้างบนที่แปลว่า "ไม่รู้จัก ⇒ ซ่อน")
  return parts.length ? `โอนเข้าบัญชี — ${parts.join(' · ')}` : 'โอนเข้าบัญชี';
}
